let currentLang = localStorage.getItem('ms_lang') || 'en';

function setLanguage(lang) {
  currentLang = lang;
  localStorage.setItem('ms_lang', lang);
  document.documentElement.lang = lang === 'ua' ? 'uk' : lang;
  document.body.classList.remove('lang-en','lang-ua','lang-pl');
  document.body.classList.add('lang-' + lang);
  const t = i18n[lang] || i18n.en;
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const k = el.dataset.i18n;
    if (t[k] !== undefined) el.textContent = t[k];
  });
  document.querySelectorAll('.lang-btn').forEach(btn =>
    btn.classList.toggle('active', btn.dataset.lang === lang)
  );
}

function getT(key) {
  const t = i18n[currentLang] || i18n.en;
  return t[key] || i18n.en[key] || key;
}

function renderPricelist(barberId) {
  const b = barbers[barberId];
  if (!b) return '';
  return b.pricelist.map(([key, price]) =>
    `<div class="price-row"><span class="price-service">${getT(key)}</span><span class="price-amount">${price}</span></div>`
  ).join('');
}
